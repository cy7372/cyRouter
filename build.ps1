#Requires -Version 7
<#
  Build cyRouter: PyInstaller exe + Inno Setup installer → Release folder.

  Pipeline:
    1. Generate icon (if stale)
    2. PyInstaller → dist/cyRouter.exe
    3. Inno Setup  → Output/cyRouter-Setup-v<ver>.exe
    4. Copy both artifacts to $ReleaseDir (default: C:\Users\CyYu\Release\cyRouter)

  Usage:
    pwsh ./build.ps1                # full build (exe + installer)
    pwsh ./build.ps1 -Clean         # clean build/dist first
    pwsh ./build.ps1 -ExeOnly       # skip Inno Setup, just produce the exe
    pwsh ./build.ps1 -Run           # build then launch exe for smoke-test
    pwsh ./build.ps1 -NoBump        # build without incrementing BUILD number
    pwsh ./build.ps1 -NoCommit      # skip auto-commit of version.py after bump
    pwsh ./build.ps1 -NoPrune       # keep all old installers (default: keep 3)
    pwsh ./build.ps1 -Version 1.2.0 # override display version (default: from version.py)
#>
[CmdletBinding()]
param(
    [switch] $Clean,
    [switch] $ExeOnly,
    [switch] $Run,
    [switch] $NoBump,
    [switch] $NoCommit,
    [switch] $NoPrune,
    [switch] $NoConfigSync,
    [string] $Version,
    [string] $ReleaseDir = "C:\Users\CyYu\Release\cyRouter"
)

$ErrorActionPreference = "Stop"
$root = $PSScriptRoot

Write-Host "==> cyRouter build" -ForegroundColor Cyan

# ── Resolve version ──────────────────────────────────────────────────
# version.py is the single source of truth. It exposes MAJOR.MINOR.PATCH.BUILD.
# - Display version (MAJOR.MINOR.PATCH) is used for .iss and file names.
# - BUILD is auto-incremented after a successful exe build (unless -NoBump).
function Read-VersionPy {
    param([string]$Path)
    $c = Get-Content $Path -Raw
    $m = [ordered]@{}
    foreach ($k in @('MAJOR','MINOR','PATCH','BUILD')) {
        if ($c -match "(?m)^\s*$k\s*=\s*(\d+)") { $m[$k] = [int]$Matches[1] }
        else { throw "Could not parse $k from $Path" }
    }
    return $m
}

$verPy = Read-VersionPy "$root/version.py"
$buildNum = $verPy.BUILD

if (-not $Version) {
    # Always four-segment: MAJOR.MINOR.PATCH.BUILD — required by Windows
    # exe version resources and shown in the installer's AppVersion.
    $Version = "$($verPy.MAJOR).$($verPy.MINOR).$($verPy.PATCH).$buildNum"
}
Write-Host "    Version: $Version"

# ── 0. Sanity checks ─────────────────────────────────────────────────
if (-not (Test-Path "$root/version.py"))   { throw "version.py not found (single source of truth)" }
if (-not (Test-Path "$root/cyRouter.spec")) { throw "cyRouter.spec not found" }
if (-not (Test-Path "$root/web/index.html")) { throw "web/index.html not found" }
if (-not (Test-Path "$root/cyRouter.iss"))  { throw "cyRouter.iss not found" }

# ── 0.6. Inject display version into cyRouter.iss ───────────────────
# cyRouter.iss carries a placeholder/old MyAppVersion; overwrite it from
# version.py so the installer and the app agree on the version string.
$issPath = "$root/cyRouter.iss"
$issRaw = Get-Content $issPath -Raw
$issPatched = [regex]::Replace(
    $issRaw,
    '#define\s+MyAppVersion\s+"[^"]*"',
    "#define MyAppVersion `"$Version`""
)
if ($issPatched -ne $issRaw) {
    Set-Content -Path $issPath -Value $issPatched -NoNewline
    Write-Host "    Patched MyAppVersion in cyRouter.iss → $Version" -ForegroundColor DarkGray
}

# ── 0.7. Generate PyInstaller version_file (VS_VERSION_INFO) ─────────
# Embeds the four-segment version into the exe's Windows version resource
# so "Right-click → Properties → Details" shows File/Product version.
$verParts = $Version.Split('.')
$vFile = "$root/packaging/version_info.txt"
$vContent = @"
# UTF-8
#
# VS_VERSION_INFO file for PyInstaller. Generated by build.ps1 from
# version.py on every build — do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($($verParts[0]), $($verParts[1]), $($verParts[2]), $($verParts[3])),
    prodvers=($($verParts[0]), $($verParts[1]), $($verParts[2]), $($verParts[3])),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          u'040904B0',
          [StringStruct(u'CompanyName', u'cyRouter'),
           StringStruct(u'FileDescription', u'cyRouter - LLM API Router'),
           StringStruct(u'FileVersion', u'$Version'),
           StringStruct(u'InternalName', u'cyRouter'),
           StringStruct(u'OriginalFilename', u'cyRouter.exe'),
           StringStruct(u'ProductName', u'cyRouter'),
           StringStruct(u'ProductVersion', u'$Version')])
      ]),
    VarFileInfo([VarStruct(u'Translation', [0x409, 1200])])
  ]
)
"@
Set-Content -Path $vFile -Value $vContent -NoNewline -Encoding UTF8
Write-Host "    Generated version_info.txt → $Version" -ForegroundColor DarkGray

# ── 0.5. Generate icon if stale ─────────────────────────────────────
$ico = "$root/packaging/cyrouter.ico"
$iconSrc = "$root/packaging/make_icon.py"
$needIcon = -not (Test-Path $ico)
if ((Test-Path $ico) -and (Test-Path $iconSrc)) {
    if ((Get-Item $iconSrc).LastWriteTime -gt (Get-Item $ico).LastWriteTime) {
        $needIcon = $true
    }
}
if ($needIcon) {
    Write-Host "==> Generating icon" -ForegroundColor Cyan
    python $iconSrc
    if ($LASTEXITCODE -ne 0) { throw "Icon generation failed" }
}

# ── 1. Clean previous artifacts ──────────────────────────────────────
if ($Clean) {
    Write-Host "==> Cleaning build/ dist/ Output/" -ForegroundColor Yellow
    Remove-Item -Recurse -Force "$root/build", "$root/dist", "$root/Output" -ErrorAction SilentlyContinue
}

# ── 2. Verify dependencies ───────────────────────────────────────────
Write-Host "==> Verifying dependencies" -ForegroundColor Cyan
$probe = @(
    "fastapi", "uvicorn", "httpx", "openai", "anthropic",
    "cryptography", "pystray", "PIL"
)
foreach ($mod in $probe) {
    python -c "import importlib,sys; sys.exit(0 if importlib.util.find_spec('$mod') else 1)" 2>&1 | Out-Null
    if ($LASTEXITCODE -ne 0) { Write-Warning "Missing dependency: $mod" }
}

# ── 3. PyInstaller ───────────────────────────────────────────────────
Write-Host "==> Running PyInstaller" -ForegroundColor Cyan
$exe = "$root/dist/cyRouter.exe"

pyinstaller --noconfirm --log-level WARN "$root/cyRouter.spec"
if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed (exit $LASTEXITCODE)" }
if (-not (Test-Path $exe)) { throw "Build finished but $exe not produced" }

$exeSizeMB = [math]::Round((Get-Item $exe).Length / 1MB, 1)
Write-Host "    exe: $exeSizeMB MB" -ForegroundColor Green

# ── 3.5. Bump BUILD number in version.py ─────────────────────────────
if (-not $NoBump) {
    $newBuild = $buildNum + 1
    $vp = "$root/version.py"
    $vpRaw = Get-Content $vp -Raw
    $vpPatched = [regex]::Replace(
        $vpRaw,
        '(?m)^(\s*BUILD\s*=\s*)\d+',
        "`${1}$newBuild"
    )
    Set-Content -Path $vp -Value $vpPatched -NoNewline
    Write-Host "    Bumped BUILD: $buildNum → $newBuild" -ForegroundColor Green

    # Auto-commit version.py so the bump is durable across rebuilds.
    if (-not $NoCommit) {
        Push-Location $root
        try {
            git add version.py 2>$null
            if ($LASTEXITCODE -eq 0) {
                git commit -m "chore(build): bump BUILD to $newBuild" 2>$null | Out-Null
                if ($LASTEXITCODE -eq 0) {
                    Write-Host "    Committed version.py (BUILD → $newBuild)" -ForegroundColor DarkGray
                }
            }
        } finally {
            Pop-Location
        }
    }
}

# ── 4. Inno Setup installer ──────────────────────────────────────────
$setupExe = $null
if (-not $ExeOnly) {
    Write-Host "==> Locating Inno Setup compiler" -ForegroundColor Cyan
    $isccCandidates = @(
        "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe",
        "C:\Program Files (x86)\Inno Setup 6\ISCC.exe",
        "C:\Program Files\Inno Setup 6\ISCC.exe"
    )
    $iscc = $null
    foreach ($p in $isccCandidates) {
        if (Test-Path $p) { $iscc = $p; break }
    }
    if (-not $iscc) {
        Write-Warning "Inno Setup (ISCC.exe) not found; skipping installer. Install via: winget install JRSoftware.InnoSetup"
    } else {
        Write-Host "    ISCC: $iscc"
        # Clean stale output dir
        Remove-Item -Recurse -Force "$root/Output" -ErrorAction SilentlyContinue

        # Inno Setup reads output dir from .iss; we just call ISCC quietly.
        $args = @("/Qp", "$root/cyRouter.iss")

        Write-Host "==> Compiling installer" -ForegroundColor Cyan
        # ISCC sometimes fails with "EndUpdateResource failed" because
        # Windows Defender locks the freshly-built exe while scanning it.
        # Retry a couple of times with a short delay.
        $maxTries = 3
        for ($try = 1; $try -le $maxTries; $try++) {
            & $iscc @args
            if ($LASTEXITCODE -eq 0) { break }
            if ($try -lt $maxTries) {
                Write-Warning "Inno Setup failed (exit $LASTEXITCODE), likely AV lock; retry $try/$($maxTries-1) in 5s..."
                Start-Sleep -Seconds 5
            }
        }
        if ($LASTEXITCODE -ne 0) { throw "Inno Setup failed (exit $LASTEXITCODE)" }

        $setupExe = "$root/Output/cyRouter-Setup.exe"
        if (-not (Test-Path $setupExe)) { throw "Inno Setup reported success but $setupExe not found" }

        $setupSizeMB = [math]::Round((Get-Item $setupExe).Length / 1MB, 1)
        Write-Host "    installer: $setupSizeMB MB" -ForegroundColor Green
    }
}

# ── 5. Publish to Release dir ────────────────────────────────────────
Write-Host "==> Publishing to $ReleaseDir" -ForegroundColor Cyan
if (-not (Test-Path $ReleaseDir)) {
    New-Item -ItemType Directory -Path $ReleaseDir -Force | Out-Null
}

# Copy the bare exe
Copy-Item $exe "$ReleaseDir/cyRouter.exe" -Force
Write-Host "    cyRouter.exe → $ReleaseDir/" -ForegroundColor Green

# Copy the installer if produced, adding version to filename
if ($setupExe) {
    $verName = "cyRouter-Setup-v$Version.exe"
    Copy-Item $setupExe "$ReleaseDir/$verName" -Force
    Write-Host "    $verName → $ReleaseDir/" -ForegroundColor Green
}

# ── 5.5. Generate version.json + prune old installers ───────────────
# version.json is a lightweight update manifest. It lives at the Release
# ROOT (parent of the cyRouter/ subdir) so nginx can serve it as a single
# top-level file. Paths inside are relative to the Release root.
$releaseRoot = Split-Path $ReleaseDir -Parent
$versionJson = [ordered]@{
    version    = $Version
    name       = "cyRouter"
    published  = (Get-Date).ToString("o")
    installer  = "cyRouter/cyRouter-Setup-v$Version.exe"
    bare_exe   = "cyRouter/cyRouter.exe"
}
$versionJsonPath = "$releaseRoot/version.json"
$versionJson | ConvertTo-Json -Depth 5 | Set-Content -Path $versionJsonPath -Encoding UTF8
Write-Host "    version.json → $releaseRoot/version.json ($Version)" -ForegroundColor Green

# Prune: keep only the 3 most recent installers (by real version sort).
# ⚠️ 不能按文件名字符串排（"v1.2.0.9" > "v1.2.0.11" 会把两位数 BUILD
# 的新包当旧包删掉，2026-09-10 就这样丢了 v1.2.0.10/11）。
if (-not $NoPrune) {
    $old = Get-ChildItem "$ReleaseDir/cyRouter-Setup-v*.exe" -ErrorAction SilentlyContinue |
        ForEach-Object {
            $v = if ($_.Name -match 'cyRouter-Setup-v([\d.]+)\.exe$') { [version]$Matches[1] } else { [version]'0.0' }
            [pscustomobject]@{ File = $_; Ver = $v }
        } |
        Sort-Object Ver -Descending |
        Select-Object -Skip 3 |
        ForEach-Object { $_.File }
    foreach ($f in $old) {
        Remove-Item -LiteralPath $f.FullName -Force
        Write-Host "    Pruned old: $($f.Name)" -ForegroundColor DarkGray
    }
}

# ── 5.7 Sync settings into the release data dir (2026-09-14) ────────
# The release exe reads config from <ReleaseDir>/data/. The installer must
# never ship settings (public artifact, no keys baked in) — but the LOCAL
# release instance then runs on whatever data/ is left there (2026-09-14:
# "v1.2.0.14 didn't detect kimi expiry" — exe was fine, its data/config.json
# was July's 101-byte default). Keep it in sync with dev at every publish:
#   • release instance running  → POST /api/config/clone from dev
#     (running instance owns config.json — a direct file write would be
#     rolled back by its in-memory snapshot on next save; port/api_keys
#     never travel via clone, keys re-encrypted against the release .key)
#   • not running               → file trio: config.json (port rewritten to
#     the release port so both coexist) + .key + usages_state.json
if (-not $NoConfigSync) {
    $devData = Join-Path $root "data"
    if (Test-Path "$devData/config.json") {
        try { $devCfg = Get-Content "$devData/config.json" -Raw | ConvertFrom-Json } catch { $devCfg = $null }
        if ($devCfg) {
            $devPort  = if ($devCfg.port) { [int]$devCfg.port } else { 20100 }
            $devApiKey = [string]@($devCfg.api_keys)[0]
            $relData = Join-Path $ReleaseDir "data"
            New-Item -ItemType Directory -Path $relData -Force | Out-Null
            # Release port: frozen default 20108, or whatever its existing config says
            $relPort = 20108
            if (Test-Path "$relData/config.json") {
                try { $relPort = [int]((Get-Content "$relData/config.json" -Raw | ConvertFrom-Json).port) } catch {}
            }
            $up = $false
            try {
                $up = Test-NetConnection -ComputerName 127.0.0.1 -Port $relPort `
                    -InformationLevel Quiet -WarningAction SilentlyContinue
            } catch { $up = $false }
            if ($up) {
                $body = @{ source_url = "http://127.0.0.1:$devPort"; source_key = $devApiKey; dry_run = $false } | ConvertTo-Json
                try {
                    Invoke-RestMethod -Uri "http://127.0.0.1:$relPort/api/config/clone" `
                        -Method Post -Body $body -ContentType "application/json" -TimeoutSec 120 | Out-Null
                    Write-Host "    settings: cloned dev → release via API (instance running on $relPort)" -ForegroundColor Green
                } catch {
                    Write-Host "    settings: clone API failed ($($_.Exception.Message)) — falling back to file copy" -ForegroundColor Yellow
                    $up = $false
                }
            }
            if (-not $up) {
                try {
                    $cfg = Get-Content "$devData/config.json" -Raw | ConvertFrom-Json
                    $cfg.port = $relPort
                    $cfg | ConvertTo-Json -Depth 100 | Set-Content -Path "$relData/config.json" -Encoding UTF8
                    Copy-Item "$devData/.key" "$relData/.key" -Force
                    if (Test-Path "$devData/usages_state.json") {
                        Copy-Item "$devData/usages_state.json" "$relData/" -Force
                    }
                    Write-Host "    settings: synced config.json(port=$relPort)+.key+usages_state → $relData" -ForegroundColor Green
                } catch {
                    Write-Host "    settings sync failed: $($_.Exception.Message)" -ForegroundColor Yellow
                }
            }
        } else {
            Write-Host "    settings sync skipped (dev config.json unreadable)" -ForegroundColor DarkGray
        }
    } else {
        Write-Host "    settings sync skipped (no dev data/config.json)" -ForegroundColor DarkGray
    }
}

# ── Summary ──────────────────────────────────────────────────────────
Write-Host ""
Write-Host "==> Build complete" -ForegroundColor Green
Write-Host ("    Version:    {0}" -f $Version)
Write-Host ("    Bare exe:   {0}\\cyRouter.exe ({1} MB)" -f $ReleaseDir,$exeSizeMB)
if ($setupExe) {
    Write-Host ("    Installer:  {0}\\cyRouter-Setup-v{1}.exe ({2} MB)" -f $ReleaseDir,$Version,$setupSizeMB)
}

# ── Optional smoke test ──────────────────────────────────────────────
if ($Run) {
    Write-Host ""
    Write-Host "==> Launching for smoke test (Ctrl+C to stop)" -ForegroundColor Cyan
    & $exe --no-browser
}
